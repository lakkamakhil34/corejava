package com.collections;

public class Car {
	
	String model;
	String brand;
	String color;
	int year;
	double price;
	
	
	public Car(String model, String brand, String color, int year, double price) {
		super();
		this.model = model;
		this.brand = brand;
		this.color = color;
		this.year = year;
		this.price = price;
	}
	
	
	
	

}
